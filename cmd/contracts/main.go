package main

import (
	"encoding/json"
	"fmt"
	"os"
	"otel/constants"
	"otel/internal/domain/reporting"
	"path/filepath"
)

func main() {
	messages := map[string]string{}
	for code, message := range constants.ErrorMessages {
		messages[code] = message
	}
	value := map[string]any{"room_statuses": constants.RoomStatusDefinitions(), "booking_statuses": constants.BookingStatusDefinitions(), "report_groups": constants.ReportGroups(), "application": constants.APPLICATION_NAME, "brandName": constants.BrandName, "brandURL": constants.BrandURL, "version": constants.COMMAND_VERSION, "application_version": constants.APPLICATION_VERSION, "commands": constants.CommandMethods, "reports": reporting.Definitions(), "report_record_kinds": reporting.Kinds, "languages": constants.SupportedLanguages(), "errors": messages}
	data, err := json.MarshalIndent(value, "", "  ")
	if err != nil {
		panic(err)
	}
	path := "ui/src/lib/contracts.generated.json"
	if len(os.Args) > 1 {
		path = os.Args[1]
	}
	if err := os.WriteFile(path, append(data, '\n'), 0644); err != nil {
		panic(err)
	}
	statusCode := "// Code generated by go run ./cmd/contracts; DO NOT EDIT.\n"
	for _, group := range []struct {
		name        string
		definitions any
		values      map[string]string
	}{
		{"RoomStatus", constants.RoomStatusDefinitions(), roomValues()},
		{"BookingStatus", constants.BookingStatusDefinitions(), bookingValues()},
	} {
		values, _ := json.MarshalIndent(group.values, "", "  ")
		definitions, _ := json.MarshalIndent(group.definitions, "", "  ")
		statusCode += fmt.Sprintf("export const %s = %s as const;\nexport type %s = typeof %s[keyof typeof %s];\nexport const %sDefinitions = %s as const;\n", group.name, values, group.name, group.name, group.name, group.name, definitions)
	}
	if err := os.WriteFile(filepath.Join(filepath.Dir(path), "statuses.generated.ts"), []byte(statusCode), 0644); err != nil {
		panic(err)
	}
}
func roomValues() map[string]string {
	m := map[string]string{}
	for _, d := range constants.RoomStatusDefinitions() {
		m[d.Key] = string(d.Value)
	}
	return m
}
func bookingValues() map[string]string {
	m := map[string]string{}
	for _, d := range constants.BookingStatusDefinitions() {
		m[d.Key] = string(d.Value)
	}
	return m
}
